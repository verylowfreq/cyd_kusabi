static bool in_ranges(const range_t *r, size_t n, uint32_t cp)
{
    size_t lo = 0;
    size_t hi = n;
    while (lo < hi) {
        const size_t mid = lo + (hi - lo) / 2;
        if (cp < r[mid].lo) {
            hi = mid;
        } else if (cp > r[mid].hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

int cdk_char_width(uint32_t cp)
{
    /* C0 / C1 制御文字。端末側で解釈するのでセルは使わない。 */
    if (cp < 0x20u || (cp >= 0x7Fu && cp < 0xA0u)) {
        return 0;
    }
    if (cp < 0x0300u) {
        return 1; /* よくある道を先に抜ける */
    }
    if (in_ranges(k_zero, sizeof(k_zero) / sizeof(k_zero[0]), cp)) {
        return 0;
    }
    if (in_ranges(k_wide, sizeof(k_wide) / sizeof(k_wide[0]), cp)) {
        return 2;
    }
    return 1;
}

bool cdk_char_ambiguous(uint32_t cp)
{
    return in_ranges(k_ambiguous, sizeof(k_ambiguous) / sizeof(k_ambiguous[0]), cp);
}
