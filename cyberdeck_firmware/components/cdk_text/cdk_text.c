/* UTF-8                                                              */
/* ------------------------------------------------------------------ */

void cdk_utf8_reset(cdk_utf8_t *d)
{
    d->acc = 0;
    d->need = 0;
    d->seen = 0;
    d->min = 0;
}

cdk_utf8_status_t cdk_utf8_feed(cdk_utf8_t *d, uint8_t b, uint32_t *cp, bool *retry)
{
    if (retry != NULL) {
        *retry = false;
    }

    if (d->need == 0) {
        if (b < 0x80u) {
            *cp = b;
            return CDK_UTF8_OK;
        }
        if ((b & 0xE0u) == 0xC0u) {
            d->acc = (uint32_t)(b & 0x1Fu);
            d->need = 1;
            d->min = 0x80u;
        } else if ((b & 0xF0u) == 0xE0u) {
            d->acc = (uint32_t)(b & 0x0Fu);
            d->need = 2;
            d->min = 0x800u;
        } else if ((b & 0xF8u) == 0xF0u) {
            d->acc = (uint32_t)(b & 0x07u);
            d->need = 3;
            d->min = 0x10000u;
        } else {
            /* 継続バイトが単独で来た、または 5 バイト以上の不正な先頭 */
            *cp = CDK_REPLACEMENT;
            return CDK_UTF8_INVALID;
        }
        d->seen = 1;
        return CDK_UTF8_NEED;
    }

    if ((b & 0xC0u) != 0x80u) {
        /* 継続バイトのはずが違うものが来た。今まで溜めたぶんを捨てて、
         * このバイトは新しい文字の先頭かもしれないので呼び側に返す。 */
        cdk_utf8_reset(d);
        *cp = CDK_REPLACEMENT;
        if (retry != NULL) {
            *retry = true;
        }
        return CDK_UTF8_INVALID;
    }

    d->acc = (d->acc << 6) | (uint32_t)(b & 0x3Fu);
    d->seen++;
    if (--d->need > 0) {
        return CDK_UTF8_NEED;
    }

    const uint32_t v = d->acc;
    const uint32_t min = d->min;
    cdk_utf8_reset(d);

    /* 冗長符号化、サロゲート、範囲外を弾く */
    if (v < min || (v >= 0xD800u && v <= 0xDFFFu) || v > 0x10FFFFu) {
        *cp = CDK_REPLACEMENT;
        return CDK_UTF8_INVALID;
    }
    *cp = v;
    return CDK_UTF8_OK;
}

size_t cdk_utf8_decode(const uint8_t *p, size_t len, uint32_t *cp, bool *ok)
{
    cdk_utf8_t d;
    cdk_utf8_reset(&d);

    for (size_t i = 0; i < len; i++) {
        bool retry = false;
        const cdk_utf8_status_t st = cdk_utf8_feed(&d, p[i], cp, &retry);
        if (st == CDK_UTF8_OK) {
            if (ok != NULL) {
                *ok = true;
            }
            return i + 1;
        }
        if (st == CDK_UTF8_INVALID) {
            if (ok != NULL) {
                *ok = false;
            }
            /* retry のときはそのバイトを消費していない */
            return retry ? i : i + 1;
        }
    }

    /* 途中で切れた */
    if (ok != NULL) {
        *ok = false;
    }
    return 0;
}

size_t cdk_utf8_encode(uint32_t cp, uint8_t *out)
{
    if (cp > 0x10FFFFu || (cp >= 0xD800u && cp <= 0xDFFFu)) {
        cp = CDK_REPLACEMENT;
    }
    if (cp < 0x80u) {
        out[0] = (uint8_t)cp;
        return 1;
    }
    if (cp < 0x800u) {
        out[0] = (uint8_t)(0xC0u | (cp >> 6));
        out[1] = (uint8_t)(0x80u | (cp & 0x3Fu));
        return 2;
    }
    if (cp < 0x10000u) {
        out[0] = (uint8_t)(0xE0u | (cp >> 12));
        out[1] = (uint8_t)(0x80u | ((cp >> 6) & 0x3Fu));
        out[2] = (uint8_t)(0x80u | (cp & 0x3Fu));
        return 3;
    }
    out[0] = (uint8_t)(0xF0u | (cp >> 18));
    out[1] = (uint8_t)(0x80u | ((cp >> 12) & 0x3Fu));
    out[2] = (uint8_t)(0x80u | ((cp >> 6) & 0x3Fu));
    out[3] = (uint8_t)(0x80u | (cp & 0x3Fu));
    return 4;
}

