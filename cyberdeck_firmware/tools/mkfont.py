def parse_bdf(path: Path) -> tuple[dict[int, list[int]], int, int]:
    """BDF を読み、{encoding: [行ごとのビット列]} と (幅, 高さ) を返す。

    行は int で表し、MSB が左端。幅 6 なら bit5..bit0 を使う。
    """
    glyphs: dict[int, list[int]] = {}
    fbb_w = fbb_h = 0
    enc = None
    bbx = None
    rows: list[int] | None = None

    with path.open("r", encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if line.startswith("FONTBOUNDINGBOX"):
                p = line.split()
                fbb_w, fbb_h = int(p[1]), int(p[2])
            elif line.startswith("ENCODING"):
                enc = int(line.split()[1])
            elif line.startswith("BBX"):
                p = line.split()
                bbx = (int(p[1]), int(p[2]), int(p[3]), int(p[4]))
            elif line == "BITMAP":
                rows = []
            elif line == "ENDCHAR":
                if enc is not None and enc >= 0 and rows is not None and bbx is not None:
                    glyphs[enc] = normalize(rows, bbx, fbb_w, fbb_h)
                enc, bbx, rows = None, None, None
            elif rows is not None:
                if line and all(c in "0123456789abcdefABCDEF" for c in line):
                    # BDF は 1 行を 8 ビット単位にパディングして 16 進で書く
                    nbits = len(line) * 4
                    rows.append((int(line, 16), nbits))

    return glyphs, fbb_w, fbb_h


def normalize(rows, bbx, fbb_w, fbb_h) -> list[int]:
    """BBX のオフセットを考慮して、幅 fbb_w x 高さ fbb_h の左詰めビット行にする。"""
    bw, bh, bx, by = bbx
    out = [0] * fbb_h

    # BDF の行は下から数えた y=by が最下行。FONTBOUNDINGBOX の descent は -2 固定。
    # ここでは fbb と bbx の descent が一致する前提で素直に上詰めする。
    top = fbb_h - bh - (by - (-2))
    for i, (val, nbits) in enumerate(rows):
        # val は nbits ビット幅で MSB 詰め。上位 bw ビットが実データ。
        bits = (val >> (nbits - bw)) & ((1 << bw) - 1) if nbits >= bw else val
        # fbb_w 幅の中で bx だけ右にずらして MSB 詰めにする
        shift = fbb_w - bw - bx
        if shift < 0:
            shift = 0
        y = top + i
        if 0 <= y < fbb_h:
            out[y] = (bits << shift) & ((1 << fbb_w) - 1)
    return out


