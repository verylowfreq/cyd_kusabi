def draw_box(up: int, right: int, down: int, left: int) -> list[int]:
    px = [[0] * CELL_W for _ in range(CELL_H)]

    v_weight = max(up, down) or LIGHT
    h_weight = max(left, right) or LIGHT
    mid_cols = V_COLS[v_weight]
    mid_rows = H_ROWS[h_weight]
    c_lo, c_hi = min(mid_cols), max(mid_cols)
    r_lo, r_hi = min(mid_rows), max(mid_rows)

    def vline(w: int, y0: int, y1: int) -> None:
        for c in V_COLS[w]:
            for y in range(y0, y1 + 1):
                px[y][c] = 1

    def hline(w: int, x0: int, x1: int) -> None:
        for r in H_ROWS[w]:
            for x in range(x0, x1 + 1):
                px[r][x] = 1

    if up:
        vline(up, 0, r_hi)
    if down:
        vline(down, r_lo, CELL_H - 1)
    if left:
        hline(left, 0, c_hi)
    if right:
        hline(right, c_lo, CELL_W - 1)

    return pack(px)


def draw_diagonals(cp: int) -> list[int]:
    px = [[0] * CELL_W for _ in range(CELL_H)]
    for y in range(CELL_H):
        x = y * (CELL_W - 1) // (CELL_H - 1)
        if cp in (0x2571, 0x2573):  # ╱
            px[CELL_H - 1 - y][x] = 1
        if cp in (0x2572, 0x2573):  # ╲
            px[y][x] = 1
    return pack(px)


