def draw_block(cp: int) -> list[int] | None:
    px = [[0] * CELL_W for _ in range(CELL_H)]

    def fill(x0, y0, x1, y1):
        for y in range(y0, y1):
            for x in range(x0, x1):
                px[y][x] = 1

    if cp == 0x2580:                       # ▀ 上半分
        fill(0, 0, CELL_W, CELL_H // 2)
    elif 0x2581 <= cp <= 0x2588:           # ▁..█ 下から n/8
        n = cp - 0x2580
        h = round(CELL_H * n / 8)
        fill(0, CELL_H - h, CELL_W, CELL_H)
    elif 0x2589 <= cp <= 0x258F:           # ▉..▏ 左から n/8
        n = 8 - (cp - 0x2588)
        w = round(CELL_W * n / 8)
        fill(0, 0, w, CELL_H)
    elif cp == 0x2590:                     # ▐ 右半分
        fill(CELL_W // 2, 0, CELL_W, CELL_H)
    elif cp in (0x2591, 0x2592, 0x2593):   # ░▒▓ 網掛け
        for y in range(CELL_H):
            for x in range(CELL_W):
                if cp == 0x2591:
                    on = (x % 2 == 0) and (y % 2 == 0)
                elif cp == 0x2592:
                    on = (x + y) % 2 == 0
                else:
                    on = not ((x % 2 == 1) and (y % 2 == 1))
                px[y][x] = 1 if on else 0
    elif cp == 0x2594:                     # ▔ 上 1/8
        fill(0, 0, CELL_W, max(1, round(CELL_H / 8)))
    elif cp == 0x2595:                     # ▕ 右 1/8
        w = max(1, round(CELL_W / 8))
        fill(CELL_W - w, 0, CELL_W, CELL_H)
    elif 0x2596 <= cp <= 0x259F:           # 四分割
        hw, hh = CELL_W // 2, CELL_H // 2
        quads = {  # (左上, 右上, 左下, 右下)
            0x2596: (0, 0, 1, 0), 0x2597: (0, 0, 0, 1),
            0x2598: (1, 0, 0, 0), 0x2599: (1, 0, 1, 1),
            0x259A: (1, 0, 0, 1), 0x259B: (1, 1, 1, 0),
            0x259C: (1, 1, 0, 1), 0x259D: (0, 1, 0, 0),
            0x259E: (0, 1, 1, 0), 0x259F: (0, 1, 1, 1),
        }
        tl, tr, bl, br = quads[cp]
        if tl:
            fill(0, 0, hw, hh)
        if tr:
            fill(hw, 0, CELL_W, hh)
        if bl:
            fill(0, hh, hw, CELL_H)
        if br:
            fill(hw, hh, CELL_W, CELL_H)
    else:
        return None
    return pack(px)


def pack(px: list[list[int]]) -> list[int]:
    """2 次元のピクセル配列を、MSB 詰めの行ビット列にする。"""
    out = []
    w = len(px[0])
    for row in px:
        v = 0
        for x, on in enumerate(row):
            if on:
                v |= 1 << (w - 1 - x)
        out.append(v)
    return out


