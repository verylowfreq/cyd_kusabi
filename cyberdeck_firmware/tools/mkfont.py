def parse_symbols(src: str) -> dict[int, list[int]]:
    """記号の点図を {codepoint: 行ビット列} に読む。"""
    out: dict[int, list[int]] = {}
    cp = None
    rows: list[str] = []

    def flush():
        if cp is None:
            return
        assert len(rows) == CELL_H, f"U+{cp:04X} の行数が {len(rows)}"
        for r in rows:
            assert len(r) == CELL_W, f"U+{cp:04X} の列数が {len(r)}"
        out[cp] = pack([[1 if c == "#" else 0 for c in r] for r in rows])

    for line in src.splitlines():
        line = line.rstrip()
        if not line:
            continue
        # 点図の行は '#' で始まりうるので、コメント判定より先に見る
        if len(line) == CELL_W and set(line) <= {".", "#"}:
            if cp is not None:
                rows.append(line)
            continue
        if line.startswith("#"):
            continue
        m = re.match(r"^([0-9A-Fa-f]{4})\s", line)
        if m:
            flush()
            cp = int(m.group(1), 16)
            rows = []
    flush()
    return out


def draw_notdef(width: int) -> list[int]:
    """げた。中を斜線で埋めた枠にして、空白と見間違えないようにする。"""
    px = [[0] * width for _ in range(CELL_H)]
    for y in range(1, CELL_H - 2):
        px[y][0] = 1
        px[y][width - 1] = 1
    for x in range(width):
        px[1][x] = 1
        px[CELL_H - 3][x] = 1
    return pack(px)


# ----------------------------------------------------------- 変換表


def jis_to_unicode(enc: int) -> int | None:
    """BDF の ENCODING (JIS X 0208 の区点を 0x2121 形式にしたもの) を Unicode に。"""
    hi = (enc >> 8) & 0xFF
    lo = enc & 0xFF
    if not (0x21 <= hi <= 0x7E and 0x21 <= lo <= 0x7E):
        return None
    try:
        s = bytes([hi | 0x80, lo | 0x80]).decode("euc_jp")
    except UnicodeDecodeError:
        return None
    if len(s) != 1:
        return None
    return ord(s)


# JIS の対応が処理系で揺れるもの。同じ字形を両方の符号位置から引けるようにする。
ALIASES = {
    0xFF5E: 0x301C,  # ～ 全角チルダ / 波ダッシュ
    0xFF0D: 0x2212,  # － / −
    0xFFE0: 0x00A2,  # ￠ / ¢
    0xFFE1: 0x00A3,  # ￡ / £
    0xFFE2: 0x00AC,  # ￢ / ¬
    0x2225: 0x2016,  # ∥ / ‖
    0x00A6: 0x007C,  # ¦ を | で代用
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bdfdir", help="shinonome-0.9.11/bdf のパス")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    d = Path(args.bdfdir)
    for name in ("shnm6x12a.bdf", "shnm6x12r.bdf", "shnmk12.bdf"):
        if not (d / name).exists():
            sys.exit(f"{d / name} がありません")

    # cp -> (is_wide, rows)
    glyphs: dict[int, tuple[bool, list[int]]] = {}

    # 1. ISO 8859-1 (半角)
    latin, lw, lh = parse_bdf(d / "shnm6x12a.bdf")
    assert (lw, lh) == (CELL_W, CELL_H), f"6x12a が {lw}x{lh}"
    for enc, rows in latin.items():
        if 0x20 <= enc <= 0xFF:
            glyphs[enc] = (False, rows)

    # 2. JIS X 0201 の半角カナ
    jisx0201, _, _ = parse_bdf(d / "shnm6x12r.bdf")
    for enc, rows in jisx0201.items():
        if 0xA1 <= enc <= 0xDF:
            glyphs[0xFF61 + (enc - 0xA1)] = (False, rows)

    # 3. JIS X 0208 (全角)
    kanji, kw, kh = parse_bdf(d / "shnmk12.bdf")
    assert (kw, kh) == (CELL_W * 2, CELL_H), f"k12 が {kw}x{kh}"
    n_kanji = 0
    for enc, rows in kanji.items():
        cp = jis_to_unicode(enc)
        if cp is None or cp > 0xFFFF:
            continue
        # Latin-1 の範囲 (° ± £ など) は JIS X 0208 にも全角で入っているが、
        # 端末はこれらを半角として数える。半角版を全角版で潰さない。
        if cp < 0x0100 and cp in glyphs:
            continue
        glyphs[cp] = (True, rows)
        n_kanji += 1

    # 別名。元がある場合だけ足す。
    for dst, src in ALIASES.items():
        if src in glyphs and dst not in glyphs:
            glyphs[dst] = glyphs[src]
        elif dst in glyphs and src not in glyphs:
            glyphs[src] = glyphs[dst]

    # 4. 罫線素片を半角で上書きする。
    #    JIS X 0208 由来の全角版がここで置き換わるのが狙い。
    n_box = 0
    for cp, arms in BOX.items():
        glyphs[cp] = (False, draw_box(*arms))
        n_box += 1
    for cp in (0x2571, 0x2572, 0x2573):
        glyphs[cp] = (False, draw_diagonals(cp))
        n_box += 1

    # 5. 記号。Ambiguous 幅で全角グリフしか無いものを半角で置き換える。
    n_sym = 0
    for cp, rows in parse_symbols(SYMBOLS_SRC).items():
        glyphs[cp] = (False, rows)
        n_sym += 1

    # 6. ブロック要素
    n_blk = 0
    for cp in range(0x2580, 0x25A0):
        rows = draw_block(cp)
        if rows is not None:
            glyphs[cp] = (False, rows)
            n_blk += 1

    # 7. 制御文字は持たない
    for cp in list(glyphs):
        if cp < 0x20 or (0x7F <= cp <= 0x9F):
            del glyphs[cp]

    # ---- 直列化 ----
    bits = bytearray()
    offsets: dict[bytes, int] = {}

    def emit(rows: list[int], wide: bool) -> int:
        nb = 2 if wide else 1
        width = CELL_W * nb
        # 行のビット列は幅ぴったり (6 または 12 ビット) で持っているが、
        # 描画側はバイトの MSB を左端として読む。左詰めに直す。
        shift = nb * 8 - width
        blob = bytearray()
        for r in rows:
            v = (r << shift) & ((1 << (nb * 8)) - 1)
            if wide:
                blob += bytes([(v >> 8) & 0xFF, v & 0xFF])
            else:
                blob += bytes([v & 0xFF])
        assert len(blob) == CELL_H * nb
        key = bytes(blob)
        if key in offsets:
            return offsets[key]  # 同じ字形は共有する (空白などが効く)
        off = len(bits)
        offsets[key] = off
        bits.extend(blob)
        return off

    notdef_half = emit(draw_notdef(CELL_W), False)
    notdef_wide = emit(draw_notdef(CELL_W * 2), True)

    cps = sorted(glyphs)
    cp_arr = bytearray()
    ent_arr = bytearray()
    for cp in cps:
        wide, rows = glyphs[cp]
        off = emit(rows, wide)
        assert off < (1 << 31)
        cp_arr += struct.pack("<H", cp)
        ent_arr += struct.pack("<I", off | (0x80000000 if wide else 0))

    header_size = 48
    cp_off = header_size
    ent_off = cp_off + len(cp_arr)
    ent_off = (ent_off + 3) & ~3
    bits_off = ent_off + len(ent_arr)

    header = bytearray(header_size)
    struct.pack_into("<4sHHBBBBI", header, 0, b"CDKF", 1, 0,
                     CELL_W, CELL_H, BASELINE, 0, len(cps))
    struct.pack_into("<IIII", header, 16, cp_off, ent_off, bits_off, len(bits))
    struct.pack_into("<II", header, 32, notdef_half, notdef_wide)

    out = bytearray(header)
    out += cp_arr
    out += b"\0" * (ent_off - len(out))
    out += ent_arr
    out += bits

    Path(args.out).write_bytes(out)

    if not args.quiet:
        print(f"{args.out}: {len(out)} バイト")
        print(f"  グリフ {len(cps)} 字 "
              f"(漢字 {n_kanji} / 罫線 {n_box} / ブロック {n_blk} / 記号 {n_sym})")
        print(f"  索引 {len(cp_arr) + len(ent_arr)} バイト / "
              f"ビットマップ {len(bits)} バイト")
    return 0


if __name__ == "__main__":
    sys.exit(main())
